def test_unit_runs_as_root_and_stops_the_container():
    unit = _UNIT.read_text()
    assert "User=root" in unit, \
        "root is required only as spawn-tier2's trusted launcher PARENT"
    assert "ExecStart=/usr/libexec/qdistro/qdistro-podapp-launch %i" in unit
    assert "ExecStop=-/usr/libexec/qdistro/qdistro-podapp-stop %i" in unit, \
        "rootless podman does not proxy SIGTERM; the container needs an " \
        "explicit admin-side stop or it outlives the unit"
    assert "Restart=no" in unit, \
        "a pod app the user closed must not be silently relaunched"
    assert "ExecStopPost=" in unit and "podapp-launch/%i.env" in unit


def test_spawn_accepts_a_precommitted_token_but_validates_it():
    """Under a unit, spawn-tier2's stdout is the journal — so the token has to
    travel the other way. It is the secctx instance-id and a directory name, so
    a malformed one must be refused rather than sanitised."""
    src = _SPAWN.read_text()
    # Anchor on the code, not the comment above it.
    idx = src.index('if [ -n "${TIER2_LAUNCH_TOKEN:-}" ]')
    window = src[idx:idx + 800]
    assert '^[0-9a-f]{32}$' in window
    assert "exit 2" in window
    # Absent the override we must still generate one.
    assert "gen_launch_token" in window


def test_dbus_policy_denies_launch_to_non_admin():
    conf = _DBUS_CONF.read_text()
    assert "LaunchPodApp" in conf, \
        "starting a User=root unit is an admin lifecycle op"
    deny = conf[conf.index('<policy context="default">'):]
    assert "LaunchPodApp" in deny


