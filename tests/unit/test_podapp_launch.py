@pytest.mark.skipif(not _PODAPPS_QML.exists(),
                    reason="qdshell checkout not present next to qdistro")
def test_shell_no_longer_forks_the_spawn_helper():
    """The regression this task exists to prevent: a click that forks
    spawn-tier2 from the unprivileged session produces an un-tagged window in
    dev and no window at all on a hardened profile."""
    qml = _PODAPPS_QML.read_text()
    launch = qml[qml.index("function launch(row)"):]
    launch = launch[:launch.index("function _registerPlaceholder")]
    assert "qdistro-tier2-spawn" not in launch
    assert "spawn-tier2" not in launch
    assert "LaunchPodApp" in launch
    assert "gdbus" in launch
    # The placeholder must key on the token the daemon returned.
    assert "_registerPlaceholder" in launch
    assert "[0-9a-f]{32}" in launch
